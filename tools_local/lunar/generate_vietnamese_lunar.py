#!/usr/bin/env python3
"""Generate CrossNext-VN's lunar year table with astronomy-engine==2.1.19."""

from bisect import bisect_right
from dataclasses import dataclass
from datetime import date, timedelta
from pathlib import Path

import astronomy

FIRST_YEAR = 1969
LAST_YEAR = 2199
VN_TIME_OFFSET = timedelta(hours=7)
TABLE = Path(__file__).resolve().parents[2] / "src/apps_local/tools/VietnameseLunarYears.inc"


@dataclass(frozen=True)
class Month:
    start: date
    length: int
    number: int
    leap: bool


def local_day(instant):
    return (instant.Utc() + VN_TIME_OFFSET).date()


def events():
    origin = astronomy.Time.Make(FIRST_YEAR - 2, 9, 1, 0, 0, 0)
    end = astronomy.Time.Make(LAST_YEAR + 2, 2, 1, 0, 0, 0)
    moons = []
    start = origin
    while start.ut < end.ut:
        next_moon = astronomy.SearchMoonPhase(0, start, 32)
        if next_moon is None:
            raise ValueError("Could not find the next new moon.")
        moons.append(local_day(next_moon))
        start = next_moon.AddDays(1)

    terms = []
    start = origin
    longitude = (int(astronomy.SunPosition(origin).elon / 30) + 1) * 30 % 360
    while start.ut < end.ut:
        next_term = astronomy.SearchSunLongitude(longitude, start, 35)
        if next_term is None:
            raise ValueError(f"Could not find the next principal term ({longitude} degrees).")
        terms.append((local_day(next_term), longitude))
        longitude = (longitude + 30) % 360
        start = next_term.AddDays(1)
    return moons, terms


def lunar_years():
    moons, terms = events()
    term_months = {bisect_right(moons, day) - 1 for day, _ in terms}
    month_elevens = [bisect_right(moons, day) - 1 for day, longitude in terms if longitude == 270]
    years = {}
    year = None
    for first, last in zip(month_elevens, month_elevens[1:]):
        count = last - first
        if count == 13:
            leap_index = next(i for i in range(first + 1, last) if i not in term_months)
        elif count == 12:
            leap_index = None
        else:
            raise ValueError(f"Unexpected solstice interval length: {count}")

        month_number = 11
        for i in range(first, last):
            leap = i == leap_index
            if i != first and not leap:
                month_number = month_number % 12 + 1
            if month_number == 1 and not leap:
                year = moons[i].year
            if year is not None:
                months = years.setdefault(year, [])
                months.append(Month(moons[i], (moons[i + 1] - moons[i]).days, month_number, leap))
    return years


def encode(year, months):
    ordinary = [month for month in months if not month.leap]
    leap = [month for month in months if month.leap]
    if [month.number for month in ordinary] != list(range(1, 13)) or len(leap) > 1:
        raise ValueError(f"Year {year} must have twelve ordinary months and at most one leap month.")
    if any(month.length not in (29, 30) for month in months):
        raise ValueError(f"Invalid month length in {year}.")
    offset = (ordinary[0].start - date(year, 1, 1)).days
    bits = sum((month.length - 29) << (16 - month.number) for month in ordinary)
    if leap:
        bits |= leap[0].number | ((leap[0].length - 29) << 16)
    return (offset << 17) | bits


def verify_known_dates(years):
    new_years = {
        1985: date(1985, 1, 21),
        2020: date(2020, 1, 25),
        2023: date(2023, 1, 22),
        2024: date(2024, 2, 10),
        2025: date(2025, 1, 29),
        2026: date(2026, 2, 17),
        2027: date(2027, 2, 6),
    }
    leap_months = {
        1985: (2, date(1985, 3, 21)),
        2020: (4, date(2020, 5, 23)),
        2023: (2, date(2023, 3, 22)),
        2025: (6, date(2025, 7, 25)),
    }
    for year, expected in new_years.items():
        actual = years[year][0].start
        if actual != expected:
            raise ValueError(f"Lunar New Year {year}: got {actual}, expected {expected}.")
    for year, expected in leap_months.items():
        month = next(month for month in years[year] if month.leap)
        if (month.number, month.start) != expected:
            raise ValueError(f"Leap month {year}: got {month}, expected {expected}.")


def main():
    years = lunar_years()
    verify_known_dates(years)
    codes = [encode(year, years[year]) for year in range(FIRST_YEAR, LAST_YEAR + 1)]
    for year in range(FIRST_YEAR, LAST_YEAR):
        last = years[year][-1]
        if last.start + timedelta(days=last.length) != years[year + 1][0].start:
            raise ValueError(f"Discontinuity after lunar year {year}.")
    source = (
        "// Generated by tools_local/lunar/generate_vietnamese_lunar.py.\n"
        "// Independent astronomical calculations with Astronomy Engine 2.1.19 (MIT), in UTC+07:00.\n"
        "// One entry per lunar year from 1969 to 2199; see docs/vietnamese-lunar-data.md.\n"
    )
    for i in range(0, len(codes), 8):
        source += "    " + ", ".join(f"0x{code:06x}" for code in codes[i:i + 8]) + ",\n"
    TABLE.write_text(source, encoding="utf-8", newline="\n")
    print(f"Generated {len(codes)} lunar years; known dates and all year boundaries verified.")


if __name__ == "__main__":
    main()

